import Foundation

// MARK: - Модель библейского стиха
struct BibleVerse: Identifiable, Codable, Hashable {
    let id: UUID
    let text: String       // Текст стиха на армянском языке
    let reference: String  // Книга, глава и стих на армянском языке
    
    init(id: UUID = UUID(), text: String, reference: String) {
        self.id = id
        self.text = text
        self.reference = reference
    }
}

